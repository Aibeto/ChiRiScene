// —— 6. 产出 ——
write(
  `${SLUG}-meta.json`,
  JSON.stringify(
    {
      slug: style.slug,
      name: style.nameEn,
      version: style.version,
      generatedAt: new Date().toISOString()
    },
    null,
    2
  )
)
write(`${SLUG}-tokens.json`, figmaTokens(style))
write(`${SLUG}-tailwind-preset.js`, tailwindPreset(style))
write(`${SLUG}-globals.css`, style.globalCss)
write(`${SLUG}-shadcn-theme.json`, shadcnTheme(style))
write(`${SLUG}-variables.css`, cssVariables(style))
write(`${SLUG}-SKILL.md`, skillMd(style))
write(`${SLUG}-ai-rules.md`, style.aiRules)
write(`${SLUG}-components.json`, JSON.stringify(style.components, null, 2))

console.log(`[pack] 完成 → ${OUT}`)
