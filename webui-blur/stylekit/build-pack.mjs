#!/usr/bin/env node
// build-pack.mjs: 把 StyleKit 的 glassmorphism 风格还原成官方「风格包」7 文件
//
// 背景：StyleKit 的导出**没有服务端下载接口**——网页上的「导出风格包 / 逐个下载」全部由浏览器
// 端 JS（/_next/static/chunks/*.js 的 exportStyleTokens / generateTailwindPresetJS / 内联模板）
// 现算现生成 Blob。因此「下载并放置资源」只能：先取权威 JSON（/api/styles/<slug>），
// 再按上游同样的模板在本地复现这 7 个文件，保证与网页导出内容一致。
//
// 用法：node webui/stylekit/build-pack.mjs
// 产出：webui/stylekit/glassmorphism/ 下的 7 个文件 + _source.json（原始 API 响应，留档）
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const HERE = dirname(fileURLToPath(import.meta.url))
const API = 'https://www.stylekit.top/api/styles/glassmorphism'
const SLUG = 'glassmorphism'
const OUT = join(HERE, SLUG)

// —— 0. 取权威数据（已存在则复用，离线可重跑）——
mkdirSync(OUT, { recursive: true })
const srcPath = join(OUT, '_source.json')
let style
try {
  const res = await fetch(API)
  if (!res.ok) throw new Error(`HTTP ${res.status}`)
  style = await res.json()
  writeFileSync(srcPath, JSON.stringify(style, null, 2))
  console.log(`[pack] 取回 ${API}（${style.aiRules.length} 字节 aiRules）`)
} catch (e) {
  style = JSON.parse(readFileSync(srcPath, 'utf8'))
  console.log(`[pack] 联网失败（${e.message}），改用本地 _source.json`)
}

const { tokens: T } = style
const write = (name, content) => {
  writeFileSync(join(OUT, name), content)
  console.log(`[pack] ${name}  ${(Buffer.byteLength(content) / 1024).toFixed(1)} KB`)
}

// —— 1. exportStyleTokens(style,"figma-tokens")：上游 chunk 模块 769908 ——
// 原实现：colors{primary,secondary,accent-N} + background/foreground 固定值 + typography 固定字体
function figmaTokens(s) {
  const accent = {}
  s.colors.accent.forEach((c, i) => {
    accent[`accent-${i + 1}`] = { value: c, type: 'color' }
  })
  return JSON.stringify(
    {
      colors: {
        primary: { value: s.colors.primary, type: 'color' },
        secondary: { value: s.colors.secondary, type: 'color' },
        accent,
        background: { value: '#ffffff', type: 'color' },
        foreground: { value: '#000000', type: 'color' }
      },
      typography: {
        fontFamily: {
          primary: { value: 'Inter, system-ui, sans-serif', type: 'fontFamily' },
          mono: { value: 'JetBrains Mono, monospace', type: 'fontFamily' }
        },
        fontSize: {
          xs: { value: '12px', type: 'fontSize' },
          sm: { value: '14px', type: 'fontSize' },
          base: { value: '16px', type: 'fontSize' },
          lg: { value: '18px', type: 'fontSize' }
        }
      }
    },
    null,
    2
  )
}

// —— 2. generateTailwindPresetJS(style,tokens)：上游 chunk 模块 333280 ——
// 上游生成的是「通用骨架 + 按 slug 的 boxShadow 特例」；glassmorphism 分支给 glass/glass-lg
function tailwindPreset(s) {
  const colors = { primary: s.colors.primary, secondary: s.colors.secondary }
  s.colors.accent.forEach((c, i) => {
    colors[`accent-${i + 1}`] = c
  })
  const preset = {
    theme: {
      extend: {
        colors,
        fontFamily: {
          heading: ['Inter', 'system-ui', 'sans-serif'],
          body: ['Inter', 'system-ui', 'sans-serif'],
          mono: ['JetBrains Mono', 'monospace']
        },
        borderRadius: { none: '0px', sm: '2px', DEFAULT: '4px', md: '6px', lg: '8px' },
        borderWidth: { DEFAULT: '1px', 2: '2px', 3: '3px', 4: '4px' },
        boxShadow: {
          glass: '0 8px 32px 0 rgba(31, 38, 135, 0.37)',
          'glass-lg': '0 12px 48px 0 rgba(31, 38, 135, 0.5)'
        }
      }
    }
  }
  return `// ${s.name} (${s.nameEn}) Tailwind CSS Preset
// Generated by StyleKit

module.exports = ${JSON.stringify(preset, null, 2)}
`
}

// —— 3. shadcn Theme：上游由 getStyleTokens + 色值换算生成 ——
