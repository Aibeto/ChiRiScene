// —— 4. CSS Variables：shadcn cssVars 的纯 CSS 形态（上游同样内联生成）——
function cssVariables(s) {
  const v = JSON.parse(shadcnTheme(s)).cssVars
  const lines = o => Object.entries(o).map(([k, val]) => `    ${k}: ${val};`).join('\n')
  return `/* ${s.name} (${s.nameEn}) - shadcn/ui Theme */
/* Generated by StyleKit */

@layer base {
  :root {
${lines(v.light)}
  }

  .dark {
${lines(v.dark)}
  }
}

@layer base {
  * {
    @apply border-border;
  }
  body {
    @apply bg-background text-foreground;
  }
}
`
}

